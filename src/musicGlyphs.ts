// Music symbols drawn as SVG shapes, so the staff never depends on a font
// downloaded from another website (school networks sometimes block those).
// Outlines come from the GNU FreeSerif font (GPL with font exception).
// Units: font units, y pointing down. Each entry says how many font units
// equal one staff space, and how far to shift the shape so that y = 0 is:
//   treble clef -> the G line, bass clef -> the F line, accidentals -> the note.
// Accidental offsets were measured from the outlines: the middle of the
// sharp's and natural's box, and the middle of the flat's bowl, sit exactly
// on the note's line or space.

export interface MusicGlyph {
  d: string;
  unitsPerSpace: number;
  offsetY: number;
  /** Left and right edges of the shape, in font units. */
  left: number;
  right: number;
}

